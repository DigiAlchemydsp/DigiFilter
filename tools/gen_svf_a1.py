#!/usr/bin/env python3
"""Generate svf_a1_tables.h: the SVF's a1 = 1/(1+g(g+k)) coefficient in Q31, for
every (FREQ index fi, resonance index qk) the SVF can select, so mode_coef needs
no software division at all.

Builds tools/gen_svf_a1.c (which includes the module's real filter.c, so the
values are bit-for-bit what div55 would have produced) for the ColdFire with the
SDK flags, runs gen() in Unicorn, and formats the filled a1table into the header.
Needs a Unicorn that executes the ColdFire EMAC (mac.l): digiemu's patched build.

    # from a digiemu checkout, with m68k-elf-gcc on PATH:
    python <DigiFilter>/tools/gen_svf_a1.py
"""
import os
import subprocess
import sys
import tempfile

from unicorn import UC_ARCH_M68K, UC_MODE_BIG_ENDIAN, Uc
from unicorn.m68k_const import UC_CPU_M68K_CFV4E, UC_M68K_REG_A7

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CROSS = os.environ.get('ELEKLOADER_CROSS', 'm68k-elf-')
BASE, STACK, RET = 0x10000, 0x200000, 0x1f0000
NROW, NCOL = 14, 128
CFLAGS = ['-mcpu=54455', '-O2', '-ffreestanding', '-fno-builtin', '-nostdlib',
          '-fno-pic', '-fno-pie', '-fomit-frame-pointer', '-Wall',
          '-ffunction-sections', '-fdata-sections', '-I', ROOT]


def build():
    d = tempfile.mkdtemp()
    elf = os.path.join(d, 'gen.elf')
    subprocess.check_call([CROSS + 'gcc'] + CFLAGS + [
        os.path.join(ROOT, 'tools', 'gen_svf_a1.c'),
        '-Wl,-Ttext=0x10000', '-Wl,-e,gen',
        '-Wl,--gc-sections', '-o', elf])
    syms = {l.split()[2]: int(l.split()[0], 16) for l in subprocess.check_output(
        [CROSS + 'nm', elf], text=True).splitlines() if len(l.split()) == 3}
    return elf, syms


def run():
    elf, sym = build()
    bin_ = elf + '.bin'
    subprocess.check_call([CROSS + 'objcopy', '-O', 'binary', elf, bin_])
    uc = Uc(UC_ARCH_M68K, UC_MODE_BIG_ENDIAN, UC_CPU_M68K_CFV4E)
    uc.mem_map(0, 0x600000)
    uc.mem_map(0x80000000, 0x20000)
    uc.mem_write(BASE, open(bin_, 'rb').read())
    uc.reg_write(UC_M68K_REG_A7, STACK - 4)
    uc.mem_write(STACK - 4, RET.to_bytes(4, 'big'))
    uc.emu_start(sym['gen'], RET, count=100000000)
    raw = uc.mem_read(sym['a1table'], NROW * NCOL * 4)
    return [[int.from_bytes(raw[(r * NCOL + c) * 4:(r * NCOL + c) * 4 + 4], 'big', signed=True)
             for c in range(NCOL)] for r in range(NROW)]


def render(table):
    out = ['/* generated by tools/gen_svf_a1.py - do not edit',
           ' * The SVF\'s a1 = floor(2^55 / ((1 << 24) + mulsh(g, g + k, 30))), g = G27[fi],',
           ' * k = K27[qk]: 1/(1 + g(g + k)) in Q31, exactly what mode_coef\'s div55 produced.',
           ' * Row qk = qi * 13 / 15 (BP); BP2 reads row qk >> 1. Column = FREQ index fi. */',
           '#ifndef SVF_A1_TABLES_H',
           '#define SVF_A1_TABLES_H',
           '',
           'static const int SVF_A1[14][128] = {']
    for r in range(NROW):
        out.append('    {')
        for i in range(0, NCOL, 6):
            out.append('        ' + ', '.join('%10d' % v for v in table[r][i:i + 6]) + ',')
        out.append('    },')
    out += ['};', '', '#endif', '']
    return '\n'.join(out)


def main():
    table = run()
    dest = os.path.join(ROOT, 'svf_a1_tables.h')
    with open(dest, 'w', newline='\n') as f:
        f.write(render(table))
    print('wrote %s (%d rows x %d)' % (dest, NROW, NCOL))
    print('row 0 first 4:', table[0][:4], 'row 13 last 4:', table[13][-4:])


if __name__ == '__main__':
    sys.exit(main())
