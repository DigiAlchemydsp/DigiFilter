#!/usr/bin/env python3
"""Generate ob1_fbsat_table.h: fbsat's correction polynomial on a 512-segment grid.

fbsat(y) is y - fmul(y, c(|y|/KF)), with
    c(z) = (5 z^2 - 2 z^4) * 4369   (Q31)
where z is Q15. The table holds c at z = i/512 for i = 0..512; the last entry is
z = 32767 for i = 512 so an index of 511 with any fraction stays in range.

This is the same integer expression and truncation as ob1_vcf.c's fbsat, so the
table is exact at the sampled points; between them the linear interpolation
tracks the polynomial (the residual is the polynomial's own integer
quantisation, ~1e-5 of full scale).
"""
import argparse
import os
import sys

N = 512
SHIFT = 6
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def correction(z):
    z2 = (z * z) >> 15
    return (5 * z2 - 2 * ((z2 * z2) >> 15)) * 4369


def render(values):
    out = [
        '/* generated by tools/gen_ob1_fbsat.py - do not edit',
        " * fbsat's correction c(|z|) = (5 z^2 - 2 z^4) * 4369, Q31, at",
        ' * z = i / 512 of KF (z is Q15). Linear interpolation between entries;',
        ' * the last entry repeats z = 32767 so z < 1 never reads past the end. */',
        '#ifndef OB1_FBSAT_TABLE_H',
        '#define OB1_FBSAT_TABLE_H',
        '',
        'static const int OB1_FBSAT_C[%d] = {' % (N + 1),
    ]
    for i in range(0, N + 1, 6):
        out.append('    ' + ', '.join('%10d' % v for v in values[i:i + 6]) + ',')
    out += ['};', '', '#endif', '']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='verify ob1_fbsat_table.h is current instead of writing it')
    args = parser.parse_args()
    values = [correction(min(i << SHIFT, 32767)) for i in range(N + 1)]
    assert all(0 <= v < (1 << 31) for v in values)
    dest = os.path.join(ROOT, 'shared', 'ob1_fbsat_table.h')
    text = render(values)
    if args.check:
        with open(dest, newline='') as f:
            if f.read() != text:
                print('%s is out of date' % dest)
                return 1
        print('%s is up to date' % dest)
        return 0
    with open(dest, 'w', newline='\n') as f:
        f.write(text)
    print('wrote %s (%d entries, %d bytes)' % (dest, N + 1, (N + 1) * 4))
    print('first 3:', values[:3], 'last 3:', values[-3:])


if __name__ == '__main__':
    sys.exit(main())
